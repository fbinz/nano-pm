const { test, expect } = require('./fixtures');

async function signIn(page, username) {
  await page.goto('/accounts/login/');
  await page.fill('input[name=username]', username);
  await page.fill('input[name=password]', username);
  await page.click('button[type=submit]');
  await page.waitForURL('/');
}

for (const [name, viewport] of Object.entries({
  desktop: { width: 1280, height: 1000 },
  mobile: { width: 390, height: 844 },
})) {
  test(`workload estimates and settings fit ${name} screens`, async ({ appPage: page }, testInfo) => {
    await page.setViewportSize(viewport);
    await page.goto('/workspaces/settings/workload/');
    await expect(page.getByRole('heading', { name: 'Workspace settings', exact: true })).toBeVisible();
    await expect(page.getByRole('switch')).toHaveCount(1);
    await expect(page.getByRole('table', { name: 'Categories', exact: true })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('workspace-settings-disabled.png'), fullPage: true });
    await expect(page.getByText('Disabling reporting prevents new estimates but preserves history.', { exact: true })).toHaveCount(0);
    await expect(page.getByRole('link', { name: 'View workload overview and history', exact: true })).toHaveCount(0);
    await page.getByLabel('Enable workload reporting', { exact: true }).check();
    await expect(page.locator('[data-workload-setting="workload_enabled"]')).toHaveAttribute('data-enabled', 'true');
    await expect(page.getByRole('switch')).toHaveCount(4);
    await expect(page.getByRole('button', { name: 'Save workload settings', exact: true })).toHaveCount(0);
    await expect(page.getByRole('link', { name: 'View workload overview and history', exact: true })).toHaveCount(0);
    const categories = page.getByRole('table', { name: 'Categories', exact: true });
    await expect(categories).toBeVisible();
    await expect(categories.locator('tbody tr')).toHaveCount(3);
    await expect(categories.getByRole('button', { name: 'Delete category', exact: true })).toHaveCount(3);
    await expect(categories.getByRole('columnheader')).toHaveText(['Category name', 'Active', 'Allow project breakdown']);
    await expect(categories.locator('tfoot #workload-new-category')).toBeVisible();
    await expect(categories.locator('#workload-new-category td')).toHaveCount(3);
    const newCategoryBox = await categories.getByLabel('New category', { exact: true }).boundingBox();
    expect(newCategoryBox.width).toBeGreaterThanOrEqual(128);
    await expect(categories.getByRole('button', { name: 'Save category' })).toHaveCount(0);
    const participation = page.getByRole('table', { name: 'Participation overrides', exact: true });
    await expect(participation).toBeVisible();
    await expect(participation.getByRole('columnheader')).toHaveText(['Person', 'Inherit', 'Included', 'Exempt']);
    await expect(participation.locator('tbody tr')).toHaveCount(4);
    await expect(participation.getByRole('radio')).toHaveCount(12);
    await expect(participation.getByRole('combobox')).toHaveCount(0);
    await expect(participation.getByRole('button', { name: 'Save participation' })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const settingsToast = page.locator('#toast-slot .workload-settings-toast');
    await expect(settingsToast).toBeVisible();
    await expect(settingsToast).toContainText('Workload settings saved.');
    const settingsBox = await settingsToast.boundingBox();
    expect(settingsBox.x).toBeGreaterThanOrEqual(0);
    expect(settingsBox.x + settingsBox.width).toBeLessThanOrEqual(viewport.width);
    expect(settingsBox.y).toBeGreaterThanOrEqual(0);
    expect(settingsBox.y + settingsBox.height).toBeLessThanOrEqual(viewport.height);
    await page.screenshot({ path: testInfo.outputPath('workload-settings-toast.png'), fullPage: true });
    await settingsToast.getByRole('button', { name: 'Dismiss' }).click();
    await expect(settingsToast).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('workload-settings.png'), fullPage: true });
    const member = participation.locator('[data-workload-member="member1"]');
    await member.getByRole('radio', { name: 'Included', exact: true }).check();
    await expect(member).toHaveAttribute('data-participation', 'included');
    const participationToast = page.locator('#toast-slot .workload-participation-toast');
    await expect(participationToast).toBeVisible();
    await expect(participationToast).toContainText('member1');
    await expect(participationToast).toContainText('Participation saved.');
    const participationBox = await participationToast.boundingBox();
    expect(participationBox.x).toBeGreaterThanOrEqual(0);
    expect(participationBox.x + participationBox.width).toBeLessThanOrEqual(viewport.width);
    expect(participationBox.y).toBeGreaterThanOrEqual(0);
    expect(participationBox.y + participationBox.height).toBeLessThanOrEqual(viewport.height);
    await page.screenshot({ path: testInfo.outputPath('workload-participation-toast.png'), fullPage: true });
    await member.getByRole('radio', { name: 'Inherit', exact: true }).check();
    await expect(member).toHaveAttribute('data-participation', 'inherit');
    await participationToast.getByRole('button', { name: 'Dismiss' }).click();
    await expect(participationToast).toHaveCount(0);
    const maintenance = categories.locator('tbody tr').first();
    await maintenance.getByLabel('Allow project breakdown', { exact: true }).check();
    await expect(maintenance).toHaveAttribute('data-supports-projects', 'true');
    await expect(maintenance.getByLabel('Allow project breakdown', { exact: true })).toBeChecked();
    const toast = page.locator('#toast-slot .workload-category-toast');
    await expect(toast).toBeVisible();
    await expect(toast).toContainText('Maintenance');
    await expect(toast).toContainText('Category saved.');
    const box = await toast.boundingBox();
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(viewport.width);
    expect(box.y).toBeGreaterThanOrEqual(0);
    expect(box.y + box.height).toBeLessThanOrEqual(viewport.height);
    await page.screenshot({ path: testInfo.outputPath('workload-category-toast.png'), fullPage: true });
    await maintenance.getByLabel('Allow project breakdown', { exact: true }).uncheck();
    await expect(maintenance).toHaveAttribute('data-supports-projects', 'false');
    await expect(maintenance.getByLabel('Allow project breakdown', { exact: true })).not.toBeChecked();
    await toast.getByRole('button', { name: 'Dismiss' }).click();
    await expect(toast).toHaveCount(0);
    const add = categories.locator('#workload-new-category');
    await add.getByLabel('New category', { exact: true }).fill('Support');
    await add.getByRole('button', { name: 'Add category' }).click();
    const support = categories.locator('[data-workload-category]', { has: page.locator('input[value="Support"]') });
    await expect(support).toHaveAttribute('data-active', 'true');
    page.once('dialog', dialog => dialog.accept());
    await support.getByRole('button', { name: 'Delete category', exact: true }).click();
    await expect(support).toHaveCount(0);
    await expect(toast).toContainText('Category deleted.');
    const deletedBox = await toast.boundingBox();
    expect(deletedBox.x).toBeGreaterThanOrEqual(0);
    expect(deletedBox.x + deletedBox.width).toBeLessThanOrEqual(viewport.width);
    expect(deletedBox.y).toBeGreaterThanOrEqual(0);
    expect(deletedBox.y + deletedBox.height).toBeLessThanOrEqual(viewport.height);
    await page.screenshot({ path: testInfo.outputPath('workload-category-deleted-toast.png'), fullPage: true });
    await toast.getByRole('button', { name: 'Dismiss' }).click();
    await expect(toast).toHaveCount(0);
    // This diagnostic captures manual editing; reminder dialogs have their own
    // behavioral coverage and should not cover the profile-link screenshot.
    await page.getByRole('switch', { name: 'Show automatic workload check-in dialogs', exact: true }).uncheck();
    await expect(page.locator('[data-workload-setting="workload_checkin_enabled"]')).toHaveAttribute('data-enabled', 'false');
    await signIn(page, 'member1');
    await page.goto('/profile/');
    const personalWorkload = page.locator('main').getByRole('link', { name: 'My workload', exact: true });
    await expect(personalWorkload).toHaveAttribute('href', '/profile/workload/');
    await page.screenshot({ path: testInfo.outputPath('profile-workload-link.png'), fullPage: true });
    await personalWorkload.click();
    await page.waitForURL('/profile/workload/');
    await expect(page.locator('main').getByRole('link', { name: 'My profile', exact: true })).toBeVisible();
    await expect(page.locator('.drawer-side .menu a[href="/profile/"]')).toHaveClass(/menu-active/);
    await expect(page.locator('.drawer-side .menu a[href="/profile/workload/"]')).toHaveCount(0);
    const donut = page.locator('[data-workload-donut]');
    await expect(donut).toBeVisible();
    await expect(page.locator('[data-workload-center-value]')).toHaveText('0%');
    const chartBox = await donut.boundingBox();
    const controlsBox = await page.locator('.workload-controls').boundingBox();
    if (name === 'desktop') expect(controlsBox.x).toBeGreaterThan(chartBox.x + chartBox.width);
    else expect(controlsBox.y).toBeGreaterThan(chartBox.y + chartBox.height);
    await page.screenshot({ path: testInfo.outputPath('my-workload-empty.png'), fullPage: true });
    await page.getByLabel('Maintenance percentage', { exact: true }).fill('30');
    await page.getByLabel('Project work percentage', { exact: true }).fill('60');
    await expect(page.locator('[data-workload-feedback]')).toHaveText('10% left to allocate');
    await expect(page.locator('[data-workload-center-value]')).toHaveText('90%');
    await page.screenshot({ path: testInfo.outputPath('my-workload-draft.png'), fullPage: true });
    await page.getByLabel('Meetings percentage', { exact: true }).fill('10');
    await expect(page.locator('#workload-total')).toHaveText('100%');
    await page.getByText('Optional project breakdown', { exact: true }).click();
    await expect(page.locator('[data-workload-project-row]:visible')).toHaveCount(0);
    await expect(page.locator('[data-workload-project-add]:visible')).toHaveCount(2);
    await page.screenshot({ path: testInfo.outputPath('my-workload-project-chips.png'), fullPage: true });
    await page.locator('.workload-projects').getByRole('button', { name: 'Add API Migration', exact: true }).click();
    await page.getByLabel('Project work: API Migration percentage', { exact: true }).fill('40');
    await page.getByRole('button', { name: 'Save estimate', exact: true }).click();
    await expect(page.locator('[data-workload-history]')).toHaveCount(1);
    await expect(page.locator('[data-workload-history]').first().locator('span[title^="Project work:"]')).toHaveAttribute('title', /Unspecified project work: 20%/);
    await expect(page.locator('#workload-total')).toHaveText('100%');
    await expect(page.locator('[data-workload-project-row]:visible')).toHaveCount(1);
    await expect(page.locator('[data-workload-project-add]:visible')).toHaveCount(1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(donut.getByRole('button', { name: 'Project work: API Migration: 40%', exact: true })).toBeVisible();
    await expect(page.locator('[data-workload-project-legend]')).toContainText('Unspecified: 20%');
    await page.screenshot({ path: testInfo.outputPath('my-workload.png'), fullPage: true });
    await page.getByText('Optional project breakdown', { exact: true }).click();
    await expect(donut.getByRole('button', { name: 'Project work: API Migration: 40%', exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('my-workload-project-ring.png'), fullPage: true });
    await page.getByText('Optional project breakdown', { exact: true }).click();
    await page.evaluate(() => window.nanoTheme.apply('dark', false));
    await page.screenshot({ path: testInfo.outputPath('my-workload-dark.png'), fullPage: true });
    await page.evaluate(() => window.nanoTheme.apply('light', false));
    await signIn(page, 'demo');
    await page.goto('/workload/overview/');
    await expect(page.locator('#workload-coverage')).toHaveText('1 of 3 participating members reported.');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('workload-overview.png'), fullPage: true });
  });
}
